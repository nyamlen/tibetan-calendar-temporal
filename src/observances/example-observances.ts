/**
 * An example observance config: how to populate one, with FPMT's published conventions.
 *
 * @remarks
 * Plain data, like `PHUGPA`, so an institution that differs spreads it, or writes a layer for
 * `composeObservances`, rather than replacing it. It is an **example** and claims no lineage. The
 * conventions at its top are FPMT's, from its page explaining the dates: "Special days which fall on
 * double days are usually celebrated on the second day, but may be celebrated on the first day if it
 * is more convenient. Special days which fall on missing days are usually celebrated on the
 * preceding day."
 *
 * Every rule that FPMT labels on its calendars was checked against those calendars for 2022-2026,
 * `test/fixtures/fpmt-observances.ts`, generated by `scripts/fetch-fpmt-observances.mjs`; the
 * residuals are listed by date in `test/validation/fpmt-observances.test.ts`. The page is
 * <https://fpmt.org/media/resources/dharma-dates/dates-explained/>.
 *
 * ## Levels
 *
 * Three, named by what a practice requires: `everyone`, `no-empowerment` and `empowerment`. The
 * assignments are authored except where `docs/observances.md` cites a publisher's notice. The
 * engine never acts on a level.
 *
 * ## English names
 *
 * The four great days and the seven anniversaries carry FPMT's own labels, word for word. The
 * Heruka, Ḍākinī and Dharma Protector days are named by their dedication, from Cornu's summary of
 * Dudjom Rinpoche. The others are authored. `docs/observances.md` gives each name's basis.
 *
 * ## Tibetan names
 *
 * Fourteen rules carry one: the four great days, Saga Dawa, sojong, the fire puja and the seven
 * persons of the anniversaries. Each is held, character for character, to `test/fixtures/observance-names.ts`,
 * which `scripts/verify-observance-names.mjs` generates from independent sources. Every other rule is
 * named in English only.
 *
 * ## What is deliberately absent
 *
 * - **Losar.** It is a calendar fact, not a convention — day 1 of month 1, or day 2 where day 1 is
 *   skipped — so it lives in the root export as `losarFor`, alongside the conversions.
 * - **Western-dated birthdays and anniversaries of a centre's own people.** The data is
 *   institution-specific and changes within a decade, so a config carries its own;
 *   `docs/guide.md` shows a worked one.
 * - **Precepts and Naga puja.** FPMT prints them, and no rule for either is known.
 * - **Eclipses**, which a front end dates.
 * - **Karma Rishi.** FPMT prints it as a seven-day period in 2026 only, and no rule for it is known.
 * - **Astrological day qualities.** The `FD-EW`, `GCH`, `NMP` codes on FPMT's calendars are the
 *   almanac's elemental and planetary attributes, not observances. The elemental ones are computed,
 *   on the `./astrology` subpath.
 *
 * ## The two inferred rules
 *
 * **Sojong** (*sojong* གསོ་སྦྱོང་; Sanskrit *poṣadha* पोषध) is a `counted` rule, inferred and not
 * sourced: it is the fit that reproduces Rabten Choeling's schedule exactly, and Rabten states no
 * method. It overrides the config's conventions with `doubledDay: "first"` and
 * `skippedDay: "following"`, the pair that fit. FPMT departs from it for one run in 2022.
 *
 * The **fire puja** is the `lunarDayPlusWeekdayMod4` formula, which agrees with FPMT's labels on
 * most days and misses a few dozen; the figure and its misses are in
 * `test/validation/fpmt-observances.test.ts`.
 *
 * @packageDocumentation
 */

