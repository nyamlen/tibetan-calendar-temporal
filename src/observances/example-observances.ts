/**
 * An example observance config, translated from FPMT's published Gelug practice dates.
 *
 * @remarks
 * Plain data, like `PHUGPA`, so an institution that differs spreads it rather than replacing it.
 * That page is also the source of the two conventions below: "Special days which fall on double days
 * are usually celebrated on the second day, but may be celebrated on the first day if it is more
 * convenient. Special days which fall on missing days are usually celebrated on the preceding day."
 *
 * Every rule comes from FPMT's page explaining what each observance is and when it falls,
 * <https://fpmt.org/media/resources/dharma-dates/dates-explained/>, and was checked against FPMT's own monthly
 * calendars for 2022-2025 — `test/fixtures/fpmt-observances.ts`, generated by
 * `scripts/fetch-fpmt-observances.mjs`. That is the difference between transcription and a tested
 * claim, and this repository has already had the transcription failure once: an early draft of
 * `docs/testing.md` hand-copied dates and put Losar 2026 on 17 February instead of 18.
 *
 * ## What is deliberately absent
 *
 * - **Losar.** It is a calendar fact, not a convention — day 1 of month 1, or day 2 where day 1 is
 *   skipped — so it lives in the root export as `losarFor`, alongside the conversions.
 * - **Teacher anniversaries.** FPMT prints many, and some are Gregorian-fixed rather than
 *   Tibetan — the Dalai Lama's birthday is 6 July. The data is institution-specific and changes
 *   within a decade, so a config may carry its own and this one ships none.
 * - **Astrological day qualities.** The `FD-EW`, `GCH`, `NMP` codes on FPMT's calendars are the
 *   almanac's elemental and planetary attributes, and they are not observances, so they are not
 *   rules here. **This said "Janson's appendices D-E, which are not computed" until 2026-09-12**, and
 *   the halves have parted company: appendix **E** is computed, on the `./astrology` subpath, which
 *   answers exactly what an `FD-EW` code says — while appendix **D**, the planets, remains out of
 *   scope. Out of *this* layer is the claim being made, not out of the package.
 * - **Sojong** (*sojong* གསོ་སྦྱོང་; Sanskrit *poṣadha* पोषध), vow renewal. It is conventionally
 *   described as falling on the full and new moon, but FPMT's calendars do not place it by day
 *   number: over 2022-2025 a fixed 15th-and-30th rule misses 38 of its occurrences and invents 36,
 *   mostly landing a day early — 31 January 2022 is day 29 and carries it, 1 February is day 30
 *   and does not. It is a **counted schedule**: the fortnight ending at a full-moon sojong is 15
 *   days, and one ending at a new-moon sojong is 14 at the end of an odd month and 15 at the end of
 *   an even one, which reproduces 96 of the 98 intervals between FPMT's sojongs of 2022-2025. A
 *   count lands on a calendar day, which is why it fell on the first of the doubled 30 of
 *   19-20 November 2025 while the great days take the second: no doubled-day convention applies.
 *   What keeps such a count in step with the moon is not yet sourced, and a count is a rule shape
 *   `ObservanceWhen` cannot yet express. So it is left out
 *   rather than shipped approximately wrong. Tracked in the pre-1.0.0
 *   checklist in `docs/roadmap.md`.
 *
 * @packageDocumentation
 */

import { deepFreeze } from "../freeze.js";
import type { ObservanceConfig } from "./types.js";

/**
 * FPMT's Gelug observance conventions and rules.
 *
 * @remarks
 * **Deeply frozen**, `rules` and each rule object included. The docs point a reader at
 * `{ ...EXAMPLE_OBSERVANCES, rules: [...EXAMPLE_OBSERVANCES.rules, mine] }`, and
 * `EXAMPLE_OBSERVANCES.rules.push(mine)` is the mistake one keystroke away from it — which used to
 * succeed and add the rule for every caller in the process.
 * Frozen recursively, nested rules included.
 */
export const EXAMPLE_OBSERVANCES: ObservanceConfig = deepFreeze({
	id: "example",
	englishName: "Example practice calendar",

	/**
	 * FPMT's guidance and its own calendars agree: the 2024 Chokhor Duchen is printed on 10 July,
	 * the second of the doubled pair. Janson's holidays section, following Berzin, says the first
	 * — which is what Kopan Monastery observed, on 9 July. Set `doubledDay: "first"` to follow
	 * that line instead.
	 */
	doubledDay: "second",

	/** The one convention both sources agree on. */
	skippedDay: "preceding",

	/**
	 * Janson says observances are "usually not celebrated in leap months". FPMT does the opposite
	 * in the case there is evidence for: the 2024 Chokhor Duchen is in leap month 6, and 4 of the
	 * regular month 6 that follows carries nothing.
	 */
	leapMonth: "leap",

	rules: [
		// ---- The great holy days, each a fixed Tibetan date ----
		{
			id: "chotrul-duchen",
			englishName: "Chotrul Duchen",
			when: { type: "annual", dates: [{ month: 1, day: 15 }] },
		},
		{
			id: "saga-dawa-duchen",
			englishName: "Saga Dawa Duchen",
			when: { type: "annual", dates: [{ month: 4, day: 15 }] },
		},
		{
			id: "chokhor-duchen",
			englishName: "Chokhor Duchen",
			when: { type: "annual", dates: [{ month: 6, day: 4 }] },
		},
		{
			id: "lhabab-duchen",
			englishName: "Lhabab Duchen",
			when: { type: "annual", dates: [{ month: 9, day: 22 }] },
		},

		// ---- The monthly cycle ----
		//
		// Every rule below overrides both day conventions, because FPMT's calendars show the
		// monthly practices behaving differently from the annual ones. Its published guidance —
		// second of a doubled pair, preceding day for a skipped one — governs "special days", and
		// the great days above follow it. The monthly cycle instead tracks the printed numbers: a
		// doubled 8th is labelled on **both** days, and a skipped 25th is simply not observed that
		// month rather than moved to the 24th. Checked against 2022-2025; with the annual
		// conventions applied instead, the monthly rules miss six occurrences and invent three.
		{
			id: "medicine-buddha",
			englishName: "Medicine Buddha puja",
			doubledDay: "both",
			skippedDay: "omit",
			when: { type: "monthly", days: [8, 15] },
		},
		{
			id: "tara",
			englishName: "Tara puja",
			doubledDay: "both",
			skippedDay: "omit",
			when: { type: "monthly", days: [8] },
		},
		{
			// FPMT records that tsog is a commitment for those who have taken a Highest Yoga Tantra
			// initiation.
			id: "heruka-day",
			englishName: "Tsog offering",
			doubledDay: "both",
			skippedDay: "omit",
			when: { type: "monthly", days: [10] },
		},
		{
			id: "dakini-day",
			englishName: "Tsog offering",
			doubledDay: "both",
			skippedDay: "omit",
			when: { type: "monthly", days: [25] },
		},
		{
			id: "dharma-protector-day",
			englishName: "Protector puja",
			doubledDay: "both",
			skippedDay: "omit",
			when: { type: "monthly", days: [29] },
		},
	],
});
