#!/usr/bin/env node

/**
 * Regenerates `test/fixtures/crosscheck-eszthoff.ts` by running eszthoff/tibetan-date-calculator.
 *
 * Usage, from a scratch directory outside this repository:
 *   mkdir -p /tmp/eszthoff && cd /tmp/eszthoff
 *   npm init -y && npm install tibetan-date-calculator@1.2.3
 *   node <path-to-repo>/scripts/fetch-eszthoff-fixtures.mjs [fromYear] [toYear]
 *
 * The package is resolved from the **current working directory**, not from this repository, and
 * is deliberately not a devDependency here. Installing it into the project would put its code in
 * the tree, and the point of the constraint below is that its code is never in the tree.
 *
 * ## Clean-room boundary — read this before touching the file
 *
 * `eszthoff/tibetan-date-calculator` has no licence file, which makes it all-rights-reserved.
 * This script **executes** it and records the dates it returns. Its source is never opened, and
 * nothing in this repository is derived from it. Computed dates are facts, not copyrightable
 * expression. Its published README is the only text consulted, which CLAUDE.md permits
 * explicitly.
 *
 * If you find yourself wanting to look at its implementation to explain a disagreement: don't.
 * Explain it from Janson instead. That is what the 23-day christian-steinert divergence was
 * resolved with, and it is the only method that keeps the licence position clean.
 */

import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { formatRow } from "./fixture-row.mjs";

const fromYear = Number(process.argv[2] ?? 2023);
const toYear = Number(process.argv[3] ?? 2027);
if (!Number.isInteger(fromYear) || !Number.isInteger(toYear) || fromYear > toYear) {
	console.error("usage: node scripts/fetch-eszthoff-fixtures.mjs [fromYear] [toYear]");
	process.exit(1);
}

// Resolve from the caller's directory so the package can live outside this repository.
const requireFromCwd = createRequire(pathToFileURL(join(process.cwd(), "package.json")));
let TibetanDate;
try {
	const entry = requireFromCwd.resolve("tibetan-date-calculator");
	({ TibetanDate } = await import(pathToFileURL(entry).href));
} catch (error) {
	console.error(
		"cannot resolve tibetan-date-calculator from the current directory.\n" +
			"Install it in a scratch directory outside this repo and run the script from there:\n" +
			"  npm init -y && npm install tibetan-date-calculator@1.2.3\n" +
			`(${error.message})`,
	);
	process.exit(1);
}

const rows = [];

let cursor = Temporal.PlainDate.from(`${fromYear}-01-01`);
const end = Temporal.PlainDate.from(`${toYear}-12-31`);
while (Temporal.PlainDate.compare(cursor, end) <= 0) {
	const iso = cursor.toString();
	// Noon, because the library builds a native Date from the string and a bare date parses as
	// UTC midnight -- which lands on the previous day west of Greenwich. The README warns about
	// exactly this, and it would shift roughly half the fixture by a day without failing.
	const d = new TibetanDate(`${iso}T12:00:00`);

	if (d.westernDateStr !== iso) {
		throw new Error(`asked for ${iso} but the library returned ${d.westernDateStr}`);
	}

	rows.push({
		iso,
		month: d.month,
		day: d.date,
		isLeapMonth: d.monthObj.isLeapMonth === true,
		isDoubledDay: d.isDoubledDay === true,
		isLeapDay: d.isLeapDay === true,
	});
	cursor = cursor.add({ days: 1 });
}

const body = rows.map(formatRow).join("\n");
const doubled = rows.filter((r) => r.isDoubledDay).length;
const leapMonthDays = rows.filter((r) => r.isLeapMonth).length;

const out = `/**
 * Day-by-day Tibetan dates for ${fromYear}-01-01 to ${toYear}-12-31, computed by
 * eszthoff/tibetan-date-calculator ${requireFromCwd("tibetan-date-calculator/package.json").version}.
 *
 * A third independent implementation of Janson, and one that follows the **almanac** value of the
 * lunar anomaly's daily increment. See docs/decisions/2026-08-12-lunar-anomaly-a2-default.md.
 *
 * @remarks
 * GENERATED by \`scripts/fetch-eszthoff-fixtures.mjs\`. Do not edit by hand — re-run the script.
 *
 * The upstream package has **no licence file**, so it is all-rights-reserved and its source is
 * never opened. This fixture records only the dates it computes, which are facts rather than
 * copyrightable expression. See the script header and CONTRIBUTING.md.
 *
 * Covers ${rows.length} consecutive days, of which ${doubled} are doubled and ${leapMonthDays}
 * fall in a leap month.
 */
import type { CrosscheckRow } from "./crosscheck-row.js";

export const ESZTHOFF_DATES: readonly CrosscheckRow[] = [
${body}
];
`;

const target = join(
	dirname(fileURLToPath(import.meta.url)),
	"..",
	"test",
	"fixtures",
	"crosscheck-eszthoff.ts",
);
writeFileSync(target, out);
process.stderr.write(
	`wrote ${rows.length} days to ${target} (${doubled} doubled, ${leapMonthDays} in leap months)\n`,
);
